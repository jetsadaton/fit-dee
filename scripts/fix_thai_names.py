def main():
    data = json.loads(INPUT.read_text())
    print(f"Loaded {len(data)} foods")

    updated = 0
    for food in data:
        fid = str(food.get("food_id") or "").strip()
        if fid in NAMES and NAMES[fid] and NAMES[fid] != "-":
            old = food.get("name_th", "")
            food["name_th"] = NAMES[fid]
            if old != NAMES[fid]:
                updated += 1

    OUTPUT.write_text(json.dumps(data, ensure_ascii=False, indent=2))
    print(f"Updated {updated} names → {OUTPUT}")

    # ดู 10 ตัวอย่าง
    sample = [f for f in data if str(f.get("food_id","")) in NAMES][:10]
    for f in sample:
        print(f"  {f['food_id']} | {f['name_th'][:30]} | {(f.get('name_en') or '')[:35]}")


if __name__ == "__main__":
    main()
